export function parseLocale(value: string | null | undefined): Locale {
  return /^ru(?:[-_]|$)/i.test(value ?? "") ? "ru" : "en";
}
export function translate(message: string, locale: Locale, values?: Record<string, string | number>): string {
  const template = locale === "ru" ? (RU[message] ?? message) : message;
  return template.replace(/[{]([A-Za-z][A-Za-z0-9_]*)[}]/g, (_whole, key: string) => String(values?.[key] ?? "{"+key+"}"));
}
export function formatNumber(value: number | null | undefined, locale: Locale): string {
  return typeof value === "number" ? new Intl.NumberFormat(locale === "ru" ? "ru-RU" : "en-US").format(value) : "—";
}
export function formatDate(value: string | null | undefined, locale: Locale): string {
  if (!value) return "—";
  const date = new Date(value);
  return Number.isFinite(date.getTime()) ? new Intl.DateTimeFormat(locale === "ru" ? "ru-RU" : "en-US", { dateStyle: "medium", timeStyle: "short" }).format(date) : "—";
}
