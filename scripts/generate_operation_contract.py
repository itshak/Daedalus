"""Emit the shared versioned launch routing contract for TypeScript."""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from daedalus.operation_manifest import MANIFEST_VERSION, coverage_manifest
from daedalus.reviewed_batch import MAX_REVIEW_BATCH, PREVIEW_ID_PATTERN, REVIEW_ENDPOINTS


def render() -> str:
    native = [name for name, workflow in coverage_manifest()["operations"].items()
              if workflow["web"] == "native" and name not in REVIEW_ENDPOINTS]
    native.append("sendResources")  # one-time shipment editor also uses its typed draft schema
    data = json.dumps(sorted(native, key=str.casefold), ensure_ascii=True)
    endpoints = json.dumps(REVIEW_ENDPOINTS, sort_keys=True, indent=2)
    return (
        "// Generated by scripts/generate_operation_contract.py; do not edit.\n"
        f"export const OPERATION_CONTRACT_VERSION = {MANIFEST_VERSION} as const;\n"
        f"export const MAX_REVIEW_BATCH = {MAX_REVIEW_BATCH} as const;\n"
        f"export const PREVIEW_ID_PATTERN = {json.dumps(PREVIEW_ID_PATTERN)} as const;\n"
        f"export const NATIVE_TASKS = {data} as const;\n"
        f"export const REVIEW_ENDPOINTS = {endpoints} as const;\n"
        "export const REVIEW_START_ROUTES = [...new Set(Object.values(REVIEW_ENDPOINTS))] as readonly string[];\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = Path(__file__).resolve().parents[1] / "apps/web/lib/generated-operation-contract.ts"
    expected = render()
    if args.check:
        if not path.exists() or path.read_text() != expected:
            raise SystemExit("Generated operation contract is stale")
    else:
        path.write_text(expected)


if __name__ == "__main__":
    main()
